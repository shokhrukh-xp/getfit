'use strict';
/* ── ПЕРЕСБОРКА ЦЕЛОГО ДНЯ ─────────────────────────────────────────────
   18.09, его слова: «тренер меня не понимает, научи его заменять программу
   дней целиком при просьбе». На скриншоте видно, как это выглядело: он просит
   снять вторые ноги и отдать день рукам — тренер отвечает ОДНОЙ заменой, он
   говорит «нет, все упражнения дня 4» — тренер снова отвечает одной.
   Причина была в коде, не в модели: changes резались до одной правки
   (slice(0,1)), приложение читало changes[0], а подсказка прямо требовала
   «одну, самую важную». Цепочкой замен день не пересобрать.
   Теперь одна правка what='day' приносит ЦЕЛУЮ новую программу, и проверяется
   здесь именно это: что приложение её применяет сразу, говорит человеку какой
   день и что стало с недельным объёмом, и не показывает поверх карточку с
   кнопкой «Другое» — отменять в ней нечего. */
const { chromium } = require('playwright');
const M = require('./mock');
let плохо = 0;
const дано = (у, т) => { console.log((у ? '  ok  ' : '  ПРОВАЛ  ') + т); if (!у) плохо++; };

const у = (id, n, м, п) => ({ id, n, en: n, m: м, q: 'machine', p: п, sets: 3, reps: '8–12', rest: 90, ss: null, why: 'по каталогу' });
const дн = (s, sub, ex) => ({ s, sub, ex });

/* было: третий день — вторые ноги, ровно его случай */
const БЫЛО = { name: 'Мышцы · 3 дня', note: 'Три дня.', focus: ['quads', 'chest'], days: [
  дн('Низ', 'ноги и ягодицы', [у('e1', 'Присед со штангой', 'quads', 'квадрицепс'), у('e2', 'Жим ногами', 'quads', 'квадрицепс'), у('e3', 'Ягодичный мостик', 'glutes', 'ягодицы')]),
  дн('Верх', 'грудь и плечи', [у('e4', 'Жим гантелей лёжа', 'chest', 'грудь'), у('e5', 'Жим стоя', 'delts', 'плечи'), у('e6', 'Тяга верхнего блока', 'lats', 'спина')]),
  дн('Низ 2', 'ноги ещё раз', [у('e7', 'Выпады с гантелями', 'quads', 'квадрицепс'), у('e8', 'Сгибание голеней', 'hams', 'бицепс бедра'), у('e9', 'Подъёмы на носки', 'calves', 'икры')]) ] };

/* стало: третий день отдан рукам и прессу, ног в нём не осталось ни одного */
const СТАЛО = { name: 'Мышцы · 3 дня', note: 'Три дня.', focus: ['quads', 'chest'], days: [
  БЫЛО.days[0], БЫЛО.days[1],
  дн('Руки', 'руки и пресс', [у('a1', 'Сгибание рук со штангой', 'biceps', 'бицепс'), у('a2', 'Разгибание рук на блоке', 'triceps', 'трицепс'), у('a3', 'Сгибание запястий', 'forearms', 'предплечья'), у('a4', 'Планка', 'abs', 'корпус')]) ] };

(async () => {
  const br = await chromium.launch();
  const page = await br.newPage({ viewport: { width: 390, height: 900 } });
  await page.route('**://cdn.jsdelivr.net/**', r => r.abort().catch(() => {}));

  let спросили = null;
  const ош = await M.поднять(page, { theme: 'dark', wait: 2800, prog: БЫЛО,
    me: { sex: 'm', age: 38, ht: 178, bw: 88.1, goal: 'muscle', wt: 'keep', gym: 'muscle', level: 'mid', place: 'gym', only: 'all', lim: [], eq: [] },
    onCoach: route => {
      спросили = JSON.parse(route.request().postData() || '{}').text || '';
      return { ok: true,
        reply: 'Понял, пересобираю день 3 под руки и пресс. Пересобрал день 3 целиком: Сгибание рук со штангой, Разгибание рук на блоке, Сгибание запястий, Планка. Подходов в неделю стало: квадрицепс 16 → 10; бицепс 3 → 9 — остальное добрал в другие дни.',
        rebuild: { prog: СТАЛО, at: Date.now(), day: 3, vol: ['квадрицепс 16 → 10', 'бицепс 3 → 9'] } };
    } });
  дано(ош.length === 0, 'страница поднялась без ошибок ' + (ош[0] || ''));

  /* ── стартовое состояние: день 3 — это ноги ── */
  const до = await page.evaluate(() => (JSON.parse(localStorage.getItem('shp_v1_ai_prog') || '{}').days || [])
    .map(d => (d.ex || []).map(x => x.n).join(', ')));
  дано(/Выпады/.test(до[2] || ''), 'до просьбы день 3 — это ноги: ' + (до[2] || '').slice(0, 60));

  /* ── просим заменить весь день ── */
  await page.click('#coachfab');
  await page.waitForTimeout(700);
  дано(await page.$eval('#coachm', e => e.classList.contains('show')).catch(() => false), 'разговор с тренером открылся');
  await page.fill('#ctext', 'Нет, все упражнения дня 3 нужно заменить на руки и пресс');
  await page.click('#csend');
  await page.waitForTimeout(1600);

  дано(/дня 3/.test(спросили || ''), 'просьба ушла тренеру целиком: ' + String(спросили).slice(0, 50));

  /* ── ГЛАВНОЕ: программа заменилась целым днём, а не одним упражнением ── */
  const после = await page.evaluate(() => (JSON.parse(localStorage.getItem('shp_v1_ai_prog') || '{}').days || [])
    .map(d => (d.ex || []).map(x => x.n).join(', ')));
  дано(!/Выпады|голеней|носки/.test(после[2] || ''),
    'ни одного прежнего упражнения дня 3 не осталось: ' + (после[2] || '').slice(0, 70));
  дано(/Сгибание рук|Разгибание рук/.test(после[2] || ''),
    'на их месте то, что он просил — руки: ' + (после[2] || '').slice(0, 70));
  дано((после[2] || '').split(',').length >= 4, 'заменён весь день, а не одно упражнение: ' + (после[2] || '').split(',').length + ' упражнения');
  дано(после[0] === до[0] && после[1] === до[1], 'дни 1 и 2 он менять не просил — они не тронуты');

  /* ── человек узнаёт об этом фактом, а не общими словами ── */
  const окна = await page.evaluate(() => window.__окна || []);
  const окно = окна.join(' | ');
  дано(/День 3 пересобран/.test(окно), 'окно называет номер дня: ' + окно.slice(0, 60));
  дано(/16 → 10/.test(окно) && /3 → 9/.test(окно), 'и показывает сдвиг недельного объёма числами');
  дано(!/новый блок/.test(окно), 'и не выдаёт это за «новый блок»: он сам попросил');

  /* ── карточки с кнопкой «Другое» быть не должно ── */
  const карточка = await page.evaluate(() => {
    const e = document.getElementById('coachreco');
    return { скрыта: !e || e.hidden, текст: (e && e.textContent || '').replace(/\s+/g, ' ').trim() };
  });
  дано(карточка.скрыта || !карточка.текст,
    'карточки замены поверх пересборки нет — отменять в ней нечего: ' + карточка.текст.slice(0, 50));

  /* ── и на самой тренировке видно новое ── */
  await page.evaluate(() => { const m = document.getElementById('coachm'); if (m) m.classList.remove('show'); });
  await page.click('.l1-in button[data-page="gym"]');
  await page.waitForTimeout(1200);
  const экран = await page.$eval('#p-gym', e => e.textContent.replace(/\s+/g, ' ')).catch(() => '');
  дано(!/Выпады с гантелями/.test(экран), 'на «Тренировке» прежних упражнений дня больше нет');

  await br.close();
  console.log(плохо ? ('ПРОВАЛОВ: ' + плохо) : 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
  process.exit(плохо ? 1 : 0);
})().catch(e => { console.error('УПАЛО:', e.stack); process.exit(1); });
