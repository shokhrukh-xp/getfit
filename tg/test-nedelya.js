'use strict';
/* Неделя мерится СВОЕЙ нормой каждого дня, а не сегодняшней.
   До 11.09 все семь столбиков сравнивались с одной нормой: в день зала она
   выше, а неделю назад вес был другой — и цвет прошлого дня мог врать.
   Проверка построена так, чтобы старый код гарантированно провалился:
   у двух дней цвет при своей норме ПРОТИВОПОЛОЖЕН цвету при общей. */
const { chromium } = require('playwright');
const M = require('./mock');
let плохо = 0;
const дано = (у, т) => { console.log((у ? '  ok  ' : '  ПРОВАЛ  ') + т); if (!у) плохо++; };
/* 08.10: дата стенда — ташкентская (M.Д), как у приложения. По UTC с 00:00 до 05:00
   Ташкента «сегодня» стенда и проверки расходились, и набор падал. */
const Д = M.Д;

/* общая норма 2110. Зал поднял норму вторника до 2450, отдых опустил среду до 1900 */
const ДНИ = [
  { date: Д(6), kcal: 2050, prot: 150, n: 3 },
  { date: Д(5), kcal: 2080, prot: 132, n: 3 },
  /* зал: съедено 2400 — это −2 % от СВОЕЙ нормы (зелёный),
     но +13,7 % от общей 2110 (красный по-старому) */
  { date: Д(4), kcal: 2400, prot: 171, n: 3, tg: { kcal: 2450, prot: 170, floor: 1600 } },
  /* отдых: съедено 2100 — это +10,5 % от СВОЕЙ нормы (красный),
     но −0,5 % от общей 2110 (зелёный по-старому) */
  { date: Д(3), kcal: 2100, prot: 158, n: 3, tg: { kcal: 1900, prot: 150, floor: 1500 } },
  { date: Д(2), kcal: 2090, prot: 146, n: 3 },
  { date: Д(1), kcal: 1960, prot: 160, n: 3 },
  { date: Д(0), kcal: 1030, prot: 128, n: 2 }
];

(async () => {
  const br = await chromium.launch();
  const page = await br.newPage({ viewport: { width: 390, height: 1400 } });
  const ош = await M.поднять(page, { theme: 'dark', time: '17:40', page: 'food',
    week: { days: ДНИ }, wait: 2200 });
  дано(ош.length === 0, 'страница поднялась без ошибок ' + (ош[0] || ''));
  await page.waitForTimeout(600);

  const столбики = await page.evaluate(() => Array.from(document.querySelectorAll('#fweek .fd'))
    .map(e => ({ подпись: e.querySelector('u').textContent, класс: e.querySelector('.fb').className })));
  дано(столбики.length === 7, 'семь столбиков: ' + столбики.length);

  const зал = столбики[2], отдых = столбики[3];
  дано(/fb-hi/.test(зал.класс),
    'день зала (2400 при своей норме 2450) — зелёный: ' + зал.класс);
  дано(!/fb-low/.test(зал.класс),
    'и НЕ красный, хотя от общей нормы это +13,7 %');
  дано(/fb-low/.test(отдых.класс),
    'день отдыха (2100 при своей норме 1900) — красный: ' + отдых.класс);
  дано(!/fb-hi/.test(отдых.класс),
    'и НЕ зелёный, хотя от общей нормы это −0,5 %');

  const строка = await page.textContent('#fweekt');
  дано(/средней норме/.test(строка),
    'подпись честно говорит «при средней норме», раз нормы разные: ' + строка);

  /* дни без своей нормы по-прежнему меряются общей */
  дано(/fb-hi/.test(столбики[0].класс) || /fb-low/.test(столбики[0].класс),
    'день без записанной нормы всё равно покрашен: ' + столбики[0].класс);

  /* 24.09, его выбор: у каждого столбика — полоса коридора СВОЕЙ нормы ±10 %.
     Проверяем геометрию, а не только наличие: зелёный столбик кончается
     внутри полосы, красный за перебор — выше неё. */
  const полосы = await page.evaluate(() => Array.from(document.querySelectorAll('#fweek .fd')).map(e => {
    const s = e.querySelector('.nb'), b = e.querySelector('.fb');
    if (!s) return null;
    const rs = s.getBoundingClientRect(), rb = b.getBoundingClientRect();
    return { норма: +s.dataset.norm, лево: rs.left, право: rs.right, факт: rb.right };
  }));
  дано(полосы.every(Boolean), 'у всех семи столбиков есть полоса нормы');
  дано(полосы[2] && полосы[2].норма === 2450 && полосы[3] && полосы[3].норма === 1900,
    'полоса — по своей норме дня: зал 2450, отдых 1900');
  дано(полосы[2] && полосы[2].факт >= полосы[2].лево - 0.5 && полосы[2].факт <= полосы[2].право + 0.5,
    'зелёный день зала кончается внутри своей полосы');
  дано(полосы[3] && полосы[3].факт > полосы[3].право,
    'красный день отдыха (+10,5 %) выходит правее своей полосы');
  дано(полосы[2] && полосы[3] && полосы[2].лево > полосы[3].лево,
    'полоса дня зала правее полосы дня отдыха — нормы разные и это видно');
  дано(/коридор нормы дня ±10 %/.test(await page.textContent('#fweekt')), 'подпись объясняет полосу');

  /* 04.10, его снимок: сегодняшняя полоса была пунктирной рамкой без заливки
     и читалась пустой при переборе. Сегодня заливается: недобор, пока день
     идёт, — нейтрально; перебор — красным, как у прошлых дней. */
  const заливка = p => p.evaluate(() => { const e = document.querySelector('#fweek .fd-today .fb'), cs = getComputedStyle(e);
    const пусто = c => c === 'transparent' || /rgba\(0, 0, 0, 0\)/.test(c);
    return { класс: e.className, фон: cs.backgroundColor, пустой: пусто(cs.backgroundColor), рамка: cs.borderTopStyle,
      красный: getComputedStyle(document.documentElement).getPropertyValue('--warn').trim() }; });
  const сегодня1 = await заливка(page);
  дано(!сегодня1.пустой && сегодня1.рамка !== 'dashed' && !/fb-low/.test(сегодня1.класс),
    'сегодня недобор (1030 из 2110), день идёт: полоса залита нейтрально, не красная: ' + JSON.stringify(сегодня1));
  await page.close();
  const page2 = await br.newPage({ viewport: { width: 390, height: 1400 } });
  await M.поднять(page2, { theme: 'dark', time: '17:40', page: 'food',
    week: { days: ДНИ.slice(0, 6).concat([{ date: Д(0), kcal: 2240, prot: 191, n: 5, tg: { kcal: 1650, prot: 160 } }]) }, wait: 2200 });
  await page2.waitForTimeout(600);
  const сегодня2 = await заливка(page2);
  дано(/fb-low/.test(сегодня2.класс) && !сегодня2.пустой && сегодня2.рамка !== 'dashed',
    'сегодня перебор (2240 при 1650): полоса залита красным, не пустая рамка: ' + JSON.stringify(сегодня2));
  const ширина = await page2.evaluate(() => { const b = document.querySelector('#fweek .fd-today .fb').getBoundingClientRect(),
    s = document.querySelector('#fweek .fd-today .nb').getBoundingClientRect(); return { факт: b.right, право: s.right }; });
  дано(ширина.факт > ширина.право, 'и выходит правее своей полосы нормы');

  await br.close();
  console.log(плохо ? '\nПРОВАЛОВ: ' + плохо : '\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
  process.exit(плохо ? 1 : 0);
})().catch(e => { console.error('УПАЛО:', e.message); process.exit(1); });
