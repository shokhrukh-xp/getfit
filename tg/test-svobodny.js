  дано(/записывать не нужно/.test(гл.строка), 'строка под часами: ' + гл.строка);
  дано(/Оценка—\s*свободный день/.test(гл.оценка.replace(/\s+/g, ' ').replace('Оценка —', 'Оценка—')) && !/\/ 1750|\/ 2110/.test(гл.оценка), 'дорожки без нормы, вместо оценки — «свободный день»: ' + гл.оценка);
