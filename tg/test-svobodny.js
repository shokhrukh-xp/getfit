  const гл = await page.evaluate(() => ({ центр: (document.querySelector('.hctr') || {}).textContent || '', плюс: document.querySelectorAll('.hb-next,.hb-todo').length,
    строка: (document.querySelector('.hnext') || {}).textContent || '', оценка: Array.from(document.querySelectorAll('.hrow')).map(r => r.textContent).join(' | ') }));
