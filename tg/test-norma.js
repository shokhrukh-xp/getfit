'use strict';
/* ── РАСКЛАДКА НОРМЫ: ЗАЛ ПО ФАКТУ И ПРИЧИНА ПОЛА ─────────────────────
   18.09, его вопрос: «почему моя норма была 1800 до тренировки и так и
   осталась после?» Разобрали — оказалось две разные вещи.
   Первая: зал входил в норму С УТРА, по расписанию, а не по факту. Его
   ответ: «показывать по факту — вдруг по плану тренировка есть, но её
   пропустят?» Он прав дважды: пропустивший весь день ел под норму
   несделанного, и снять её было нечем; а личный коэффициент k и без того
   считается по дням с ЗАПИСАННОЙ тренировкой — норма спорила с моделью,
   которая её же правит.
   Вторая: у него норма упёрлась в пол, и пол этот — основной обмен, а
   экран объяснял верное число словами «пол по жиру». Пол бывает двух
   видов, и какой именно сработал, знает сервер (floorWhy).
   24.09 он выбрал подпись: «нижняя граница плана» — одна на оба вида.
   «Пол по жиру / по обмену» звучит как физиологический предел, а число —
   правило приложения. Проверяем, что подпись одна и ни в одном случае не
   выдаёт себя за физиологию. */
const { chromium } = require('playwright');
const M = require('./mock');
let плохо = 0;
const дано = (у, т) => { console.log((у ? '  ok  ' : '  ПРОВАЛ  ') + т); if (!у) плохо++; };

const еда = async page => {
  await page.click('.l1 button[data-page="food"]');
  await page.waitForTimeout(900);
  return (await page.$eval('.fparts', e => e.textContent.replace(/\s+/g, ' ').trim()).catch(() => ''));
};

(async () => {
  /* ── 1. день зала, тренировки ещё нет ── */
  const br = await chromium.launch();
  const p1 = await br.newPage({ viewport: { width: 390, height: 900 } });
  await p1.route('**://cdn.jsdelivr.net/**', r => r.abort().catch(() => {}));
  const ош = await M.поднять(p1, { theme: 'dark', wait: 2600, day: { gymPlan: true,
    targets: { kcal: 1800, prot: 160, fib: 30, floorWhy: 'обмен',
      parts: { base: 2270, gym: 0, acts: 0, plan: 0, delta: -470, floor: 1, k: 1 } } } });
  дано(ош.length === 0, 'страница поднялась без ошибок ' + (ош[0] || ''));
  const до = await еда(p1);
  дано(!/зал \d/.test(до), 'до тренировки зала в раскладке нет: ' + до.slice(0, 64));
  дано(/день зала/.test(до) && /после тренировки/.test(до),
    'и сказано, что он войдёт после неё: ' + (до.split('<')[0] || до).slice(-70));
  дано(/по её минутам и темпу/.test(до), 'и по чему именно его посчитают');

  /* ── 2. пол назван границей плана, а не физиологией (его выбор 24.09) ── */
  дано(/нижняя граница плана/.test(до), 'пол назван правильно: ' + (до.match(/пол по [^,]+/) || ['—'])[0]);
  дано(!/пол по жиру/.test(до), 'и это не выдаётся за пол по жиру');
  await p1.close();

  /* ── 3. у кого есть замер состава — пол другой, а подпись та же ── */
  const p2 = await br.newPage({ viewport: { width: 390, height: 900 } });
  await p2.route('**://cdn.jsdelivr.net/**', r => r.abort().catch(() => {}));
  await M.поднять(p2, { theme: 'dark', wait: 2600, day: { gymPlan: false,
    targets: { kcal: 1950, prot: 160, fib: 30, floorWhy: 'жир',
      parts: { base: 2270, gym: 270, acts: 0, plan: 0, delta: -590, floor: 1, k: 1,
               gymMin: 45, gymSets: 18, gymMet: 5, gymTempo: 'плотный' } } } });
  const жир = await еда(p2);
  дано(/нижняя граница плана/.test(жир), 'ограничение названо границей плана: ' + (жир.match(/пол по [^,]+/) || ['—'])[0]);
  дано(!/основному обмену/.test(жир), 'и не подменён обменом');
  await p2.close();

  /* ── 4. после тренировки зал появляется слагаемым, обещание уходит ── */
  const p3 = await br.newPage({ viewport: { width: 390, height: 900 } });
  await p3.route('**://cdn.jsdelivr.net/**', r => r.abort().catch(() => {}));
  await M.поднять(p3, { theme: 'dark', wait: 2600, day: { gymPlan: false,
    targets: { kcal: 2050, prot: 160, fib: 30,
      parts: { base: 2270, gym: 270, acts: 0, plan: 0, delta: -490, floor: 0, k: 1,
               gymMin: 45, gymSets: 18, gymMet: 5, gymTempo: 'плотный' } } } });
  const после = await еда(p3);
  дано(/зал 270/.test(после), 'после тренировки зал стоит слагаемым: ' + после.slice(0, 60));
  дано(!/войдёт в норму/.test(после), 'и обещание «войдёт после тренировки» пропало');
  дано(/45 минут и 18 подходов/.test(после) && /темп плотный/.test(после),
    'видно, из чего он взялся: ' + (после.match(/зал: [^·]+/) || ['—'])[0].slice(0, 56));
  дано(/− 490 по цели/.test(после), 'а дефицит назван целью, раз пола нет: ' + (после.match(/[−+] \d+ [^·]*/) || ['—'])[0].slice(0, 30));

  /* раскладка обязана сходиться в уме — он складывает её сам */
  const ч = после.match(/норма (\d+) = база (\d+) \+ зал (\d+) − (\d+)/);
  дано(!!ч && (+ч[2] + +ч[3] - +ч[4]) === +ч[1], 'и сходится: ' + (ч ? ч[2] + ' + ' + ч[3] + ' − ' + ч[4] + ' = ' + ч[1] : '—'));
  await p3.close();

  await br.close();
  console.log(плохо ? ('ПРОВАЛОВ: ' + плохо) : 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ');
  process.exit(плохо ? 1 : 0);
})().catch(e => { console.error('УПАЛО:', e.stack); process.exit(1); });
